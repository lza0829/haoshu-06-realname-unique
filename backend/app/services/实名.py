"""实名链接唯一 · 甲口径：先到保留、后到拒绝（全局只此一种）。

一号卡至多一条有效实名链接：
- 写闸：装载号卡-客户链接时，该卡已有有效实名而客户不同 → 抛 实名冲突，整批失败闭回滚；
- 审计：拒绝证据落 实名冲突证据 表（随隔离匣同事务另写，不随业务批回滚），禁止无证据静默改挂；
- 贯验：查双实名() 检正式侧双有效残留；实名唯一概览() 为只读接口（号卡→有效客户→拒绝证据）；
- 不得半替换：先到从不被断，后到冲突即整票回滚，正式侧永不双有效。
"""

from app.db import 连接
from app.seed import 此刻

口径 = "先到保留·后到拒绝"


class 实名冲突(Exception):
    """号卡已有有效实名链接，后到不同客户被拒绝。携带结构化证据字段。"""

    def __init__(self, 号卡业务键: str, 保留客户业务键: str, 冲突客户业务键: str, 批号: str):
        self.号卡业务键 = 号卡业务键
        self.保留客户业务键 = 保留客户业务键
        self.冲突客户业务键 = 冲突客户业务键
        self.批号 = 批号
        super().__init__(
            f"实名冲突:{号卡业务键} 已实名 {保留客户业务键}，拒绝后到 {冲突客户业务键}（{批号}）"
        )


def 记拒绝证据(conn, 冲突: 实名冲突) -> None:
    """业务批回滚后另写拒绝证据：证据不进业务事务，须事后可查。"""
    conn.execute(
        "INSERT INTO 实名冲突证据(号卡业务键, 保留客户业务键, 冲突客户业务键, 批号, 处置, 时刻)"
        " VALUES (?,?,?,?,?,?)",
        (冲突.号卡业务键, 冲突.保留客户业务键, 冲突.冲突客户业务键, 冲突.批号, "拒绝", 此刻()),
    )


def 查双实名(conn) -> list[str]:
    """正式侧残留检查：同号卡多于一条实名链接即双有效，贯验须败。"""
    问题 = []
    for r in conn.execute(
        "SELECT 号卡哈希, COUNT(*) AS c FROM 链接_号卡客户 GROUP BY 号卡哈希 HAVING c>1"
    ):
        卡 = conn.execute("SELECT 业务键 FROM 枢纽_号卡 WHERE 哈希键=?", (r["号卡哈希"],)).fetchone()
        问题.append(f"{卡['业务键'] if 卡 else r['号卡哈希']}:{r['c']}条")
    return 问题


def 实名唯一概览() -> dict:
    """实名唯一贯验只读接口：每号卡的有效实名客户与冲突拒绝证据。只读，不写库。"""
    conn = 连接()
    try:
        卡表: dict[str, dict] = {}
        for r in conn.execute(
            """SELECT a.业务键 AS 号卡业务键, b.业务键 AS 客户业务键
               FROM 链接_号卡客户 l
               JOIN 枢纽_号卡 a ON a.哈希键 = l.号卡哈希
               JOIN 枢纽_客户 b ON b.哈希键 = l.客户哈希
               ORDER BY a.业务键"""
        ):
            卡表.setdefault(r["号卡业务键"], {"客户": [], "证据": []})["客户"].append(r["客户业务键"])
        for r in conn.execute("SELECT * FROM 实名冲突证据 ORDER BY 编号"):
            卡表.setdefault(r["号卡业务键"], {"客户": [], "证据": []})["证据"].append(
                {
                    "处置": r["处置"],
                    "保留客户业务键": r["保留客户业务键"],
                    "冲突客户业务键": r["冲突客户业务键"],
                    "批号": r["批号"],
                    "时刻": r["时刻"],
                }
            )
        号卡 = []
        for 键, 项 in sorted(卡表.items()):
            唯一 = len(项["客户"]) == 1
            号卡.append(
                {
                    "号卡业务键": 键,
                    "有效客户": 项["客户"][0] if 唯一 else None,
                    "实名链接数": len(项["客户"]),
                    "异常": "" if 唯一 else f"双有效残留:{'、'.join(项['客户'])}",
                    "证据": 项["证据"],
                }
            )
        return {
            "口径": 口径,
            "是否全部唯一": all(x["实名链接数"] == 1 for x in 号卡),
            "号卡": 号卡,
        }
    finally:
        conn.close()
